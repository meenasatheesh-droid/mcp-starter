// Helper to generate dynamic candlesticks for interactive charts
export function generateCandleData(asset: MarketAsset, timeframe: string): Candle[] {
  const pointsCount = timeframe === '1D' ? 48 : timeframe === '5D' ? 60 : timeframe === '1M' ? 30 : 60;
  const basePrice = asset.price;
  const volatility = asset.category === 'crypto' ? 0.022 : asset.category === 'forex' ? 0.003 : 0.012;
  
  const candles: Candle[] = [];
  let currentClose = basePrice * (1 - (asset.changePercent / 100));

  const now = new Date();

  for (let i = 0; i < pointsCount; i++) {
    const timeOffsetMinutes = (pointsCount - i) * (timeframe === '1D' ? 10 : timeframe === '5D' ? 60 : 1440);
    const candleTime = new Date(now.getTime() - timeOffsetMinutes * 60 * 1000);
    
    // Random walk with drift towards current price
    const drift = (basePrice - currentClose) / (pointsCount - i);
    const delta = (Math.sin(i * 0.4) * 0.5 + (Math.random() - 0.48)) * currentClose * volatility;
    
    const open = currentClose;
    let close = open + delta + drift;
    if (i === pointsCount - 1) {
      close = basePrice;
    }
    
    const high = Math.max(open, close) + Math.random() * currentClose * (volatility * 0.7);
    const low = Math.min(open, close) - Math.random() * currentClose * (volatility * 0.7);
    const volume = Math.floor(Math.random() * 50000 + 10000);

    const timeString = timeframe === '1D' 
      ? candleTime.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      : candleTime.toLocaleDateString([], { month: 'short', day: 'numeric' });

    candles.push({
      time: timeString,
      open: parseFloat(open.toFixed(asset.digits ?? 2)),
      high: parseFloat(high.toFixed(asset.digits ?? 2)),
      low: parseFloat(low.toFixed(asset.digits ?? 2)),
      close: parseFloat(close.toFixed(asset.digits ?? 2)),
      volume,
    });

    currentClose = close;
  }

  return candles;
}
